#!/usr/bin/env node
/**
 * Scans apps/docs/examples/<component>/<example>.tsx and writes lib/examples.generated.ts:
 * a map from example name → next/dynamic component, so previews only load the examples a page shows.
 * Runs before `dev`, `build` and `typecheck`. Idempotent; writes only when the output changes.
 */
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const examplesDir = path.join(root, 'examples');
const outFile = path.join(root, 'lib', 'examples.generated.ts');

/** @type {{ key: string; component: string; file: string }[]} */
const entries = [];
if (existsSync(examplesDir)) {
  for (const component of readdirSync(examplesDir).sort()) {
    const dir = path.join(examplesDir, component);
    if (!statSync(dir).isDirectory()) continue;
    for (const file of readdirSync(dir).sort()) {
      if (!file.endsWith('.tsx')) continue;
      entries.push({ key: file.slice(0, -4), component, file: file.slice(0, -4) });
    }
  }
}

const seen = new Map();
for (const e of entries) {
  if (seen.has(e.key)) {
    console.warn(`gen-examples: "${e.key}" exists in both examples/${seen.get(e.key)} and examples/${e.component}; keeping the first.`);
    continue;
  }
  seen.set(e.key, e.component);
}
const unique = entries.filter((e, i) => entries.findIndex((x) => x.key === e.key) === i);

const lines = [
  '// Generated by scripts/gen-examples.mjs — do not edit by hand.',
  "'use client';",
  '',
  "import dynamic from 'next/dynamic';",
  "import type { ComponentType } from 'react';",
  '',
  '/** Example name → lazily loaded component. */',
  'export const examples: Record<string, ComponentType> = {',
  ...unique.map((e) => `  ${JSON.stringify(e.key)}: dynamic(() => import('../examples/${e.component}/${e.file}')),`),
  '};',
  '',
  '/** Example name → component folder, e.g. "button-demo" → "button". */',
  'export const exampleComponent: Record<string, string> = {',
  ...unique.map((e) => `  ${JSON.stringify(e.key)}: ${JSON.stringify(e.component)},`),
  '};',
  '',
];
const next = lines.join('\n');
const prev = existsSync(outFile) ? readFileSync(outFile, 'utf8') : '';
if (prev !== next) writeFileSync(outFile, next);
console.log(`gen-examples: ${unique.length} examples from ${new Set(unique.map((e) => e.component)).size} components${prev === next ? ' (unchanged)' : ''}`);
